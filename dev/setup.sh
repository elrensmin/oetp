#!/usr/bin/env bash
# OETP dev environment setup
# Generates device/ledger/beacon keys, writes dev/.env, and creates sample data.
set -euo pipefail

cd "$(dirname "$0")/.."

DEV_DIR="./dev"
mkdir -p "$DEV_DIR/cache" "$DEV_DIR/queue" "$DEV_DIR/ledger"

echo "generating device Ed25519 key..."
DEVICE_KEY=$(openssl genpkey -algorithm ed25519 -outform DER 2>/dev/null | tail -c 32 | xxd -p -c 64)
echo "$DEVICE_KEY" > "$DEV_DIR/device.key"
chmod 600 "$DEV_DIR/device.key"

echo "generating device X25519 key..."
DEVICE_X25519_KEY=$(openssl genpkey -algorithm x25519 -outform DER 2>/dev/null | tail -c 32 | xxd -p -c 64)
echo "$DEVICE_X25519_KEY" > "$DEV_DIR/device_x25519.key"
chmod 600 "$DEV_DIR/device_x25519.key"

echo "generating ledger signing key..."
LEDGER_KEY=$(openssl genpkey -algorithm ed25519 -outform DER 2>/dev/null | tail -c 32 | xxd -p -c 64)
echo "$LEDGER_KEY" > "$DEV_DIR/ledger.key"
chmod 600 "$DEV_DIR/ledger.key"

echo "generating beacon signing key..."
BEACON_KEYPAIR=$(cargo run --release -p oetp-ledger -- keygen 2>/dev/null)
BEACON_KEY=$(echo "$BEACON_KEYPAIR" | head -1)
BEACON_PUB=$(echo "$BEACON_KEYPAIR" | tail -1)
echo "$BEACON_KEY" > "$DEV_DIR/beacon.key"
chmod 600 "$DEV_DIR/beacon.key"

EXAM_SALT=$(openssl rand -hex 32)
SERVER_PEPPER=$(openssl rand -hex 32)
TENANT_MASTER_KEY=$(openssl rand -hex 32)

API_KEY="dev-api-key-12345678-with-enough-characters"

cat > "$DEV_DIR/.env" <<ENVEOF
