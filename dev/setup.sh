# shellcheck disable=all

# === Edge Daemon ===
OETP_TENANT_ID=nta
OETP_EXAM_ID=jee-2027
OETP_DEVICE_ID=device-01
OETP_CENTER_ID=center-01
OETP_LEDGER_URL=http://localhost:8081
OETP_BEACON_URL=http://localhost:9090
OETP_LISTEN_ADDR=127.0.0.1:8080
OETP_DEVICE_KEY=${PWD}/dev/device.key
OETP_DEVICE_X25519_KEY=${PWD}/dev/device_x25519.key
OETP_CACHE_DIR=${PWD}/dev/cache
OETP_QUEUE_DIR=${PWD}/dev/queue
OETP_BEACON_PUBLIC_KEY=${BEACON_PUB}
OETP_EXAM_SALT=${EXAM_SALT}
OETP_SERVER_PEPPER=${SERVER_PEPPER}
OETP_API_KEY=${API_KEY}

# === Ledger ===
OETP_LEDGER_LISTEN_ADDR=0.0.0.0:8081
OETP_LEDGER_DB_PATH=${PWD}/dev/ledger.db
OETP_SIGNING_KEY=${LEDGER_KEY}
OETP_ANCHOR_RPC_URL=http://localhost:8545

# === Beacon ===
OETP_BEACON_LISTEN_ADDR=0.0.0.0:9090
OETP_BEACON_SIGNING_KEY=${BEACON_KEY}

# === Shared ===
OETP_TENANT_MASTER_KEY=${TENANT_MASTER_KEY}

# === Logging ===
RUST_LOG=info
ENVEOF

chmod 600 "$DEV_DIR/.env"
echo "wrote $DEV_DIR/.env"

